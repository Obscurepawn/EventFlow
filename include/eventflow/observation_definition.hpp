#pragma once
#include "eventflow/types.hpp"
#include <map>
#include <optional>

namespace eventflow {
enum class ObservationInputKind {
  Source,
  RelationChange,
  AttemptSettled,
  RequestTerminal,
  Clock,
  ExpiryNotice
};
enum class ObservationProgramKind { Fsm, Cep };

struct ObservationInputDefinition {
  std::string id;
  ObservationInputKind kind = ObservationInputKind::Source;
  std::string event_kind;
  std::optional<std::uint32_t> relation;
  std::string source_kind;
  std::string plan;
  std::string policy_id;
  // AttemptSettled has one target; RequestTerminal lists the host plan's exact targets.
  std::vector<std::uint32_t> completion_targets;
  std::uint8_t change_mask = 7;
  // Only Source declares its payload. Other input layouts are generated by Catalog.
  std::vector<Field> source_fields;
  std::size_t max_event_bytes = 64 * 1024;
};

struct ObservationReadDefinition {
  std::string alias;
  std::uint32_t relation = 0;
  std::vector<Field> fields;
  std::size_t max_row_bytes = 64 * 1024;
};

struct ObservationRuleDefinition {
  std::string name;
  std::uint64_t version = 1;
  ObservationProgramKind program_kind = ObservationProgramKind::Fsm;
  std::string recipe_id;
  std::uint64_t recipe_version = 1;
  std::string implementation_identity;
  // Canonical JSON object describing the immutable program, excluding callback addresses.
  std::string program_fingerprint;
  std::vector<Field> scope_fields;
  std::vector<ObservationInputDefinition> inputs;
  std::vector<ObservationReadDefinition> reads;
  std::optional<std::uint32_t> sink_relation;
  std::size_t max_sink_row_bytes = 0;
  // Exact FunctionView/request-lineage SQL targets of the host's activated Request plans.
  std::vector<std::uint32_t> activation_targets;
};

struct ObservationRuleDescriptor {
  std::uint32_t id = 0;
  // Reconstructs Catalog definition order without changing older relation wire layouts.
  std::size_t after_relation_count = 0;
  ObservationRuleDefinition definition;
  // Aligned with inputs. Change payloads: op/has_before/has_after/before_*/after_*.
  // Host candidate_epoch uses a canonical decimal String, preserving the UInt64 range.
  std::vector<std::vector<Field>> event_fields;
};

struct ObservationGraph {
  // Derived only; neither index nor topological order is independently editable metadata.
  std::map<std::uint32_t, std::vector<std::uint32_t>>
      subscribers_by_relation; // Change inputs only.
  std::vector<std::uint32_t> rule_order;
};
} // namespace eventflow
